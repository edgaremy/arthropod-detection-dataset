"""Visualize False Positives (FP) and False Negatives (FN) from validation metrics.

This script creates a PNG grid showing examples of:
- Images with False Positives (model predicted arthropods where there are none)
- Images with False Negatives (model missed actual arthropods)

The script reads validation metrics from CSV files generated by get_validation_metrics.py
and outputs a visualization grid to help analyze model failures.

Usage:
    python visualize_FP_and_FN.py

Requirements:
    - matplotlib
    - numpy
    - opencv-python (cv2)
    - ultralytics (YOLO)
    - scipy
"""

import csv
import os
from pathlib import Path
import random
from scipy.optimize import linear_sum_assignment

import cv2
import matplotlib.pyplot as plt
import matplotlib.patches as patches
import numpy as np
from tqdm import tqdm

# Configuration
SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent

# Paths
METRICS_CSV = REPO_ROOT / "validation/metrics/validation_arthro_and_flatbug.csv"
MODEL_PATH = REPO_ROOT / "runs/arthro_and_flatbug/train/weights/best.pt"
DATASET_PATH = REPO_ROOT / "dataset"
OUTPUT_PNG = SCRIPT_DIR / "FP_FN_examples_grid.png"

# Grid configuration
N_COLS = 5  # Number of columns in the grid
N_FP = 10  # Number of FP examples to show
N_FN = 10  # Number of FN examples to show
GRID_DPI = 150
IMAGE_SIZE = (512, 512)  # Maximum size for images (maintain aspect ratio)

# Colors
FP_COLOR = "#ff6b6b"  # Red for false positives
FN_COLOR = "#4ecdc4"  # Teal for false negatives
TP_COLOR = "#90EE90"  # Light green for true positives
PRED_COLOR = "#f9ca24"  # Yellow for predictions


def load_yolo_model(model_path):
    """Load YOLO model for inference."""
    from ultralytics import YOLO
    return YOLO(str(model_path))


def get_image_paths_for_taxon(taxon_id, split="test"):
    """Get all image paths for a given taxon_id in the specified split."""
    images_dir = DATASET_PATH / "images" / split
    if not images_dir.exists():
        return []
    
    # Find all images starting with this taxon_id
    image_files = []
    for ext in ["*.jpg", "*.jpeg", "*.png"]:
        for img_file in images_dir.glob(ext):
            if img_file.stem.startswith(str(taxon_id)):
                image_files.append(img_file)
    
    return sorted(image_files)


def yolo_to_xyxy(xc, yc, w, h, img_w, img_h):
    """Convert YOLO format (normalized center x, center y, width, height) to xyxy."""
    x1 = int((xc - w / 2.0) * img_w)
    y1 = int((yc - h / 2.0) * img_h)
    x2 = int((xc + w / 2.0) * img_w)
    y2 = int((yc + h / 2.0) * img_h)
    return x1, y1, x2, y2


def load_ground_truth_boxes(label_path, img_w, img_h):
    """Load ground truth bounding boxes from YOLO label file."""
    boxes = []
    if not label_path.exists():
        return boxes
    
    with open(label_path, 'r') as f:
        for line in f:
            parts = line.strip().split()
            if len(parts) != 5:
                continue
            try:
                _, xc, yc, bw, bh = map(float, parts)
                x1, y1, x2, y2 = yolo_to_xyxy(xc, yc, bw, bh, img_w, img_h)
                boxes.append((x1, y1, x2, y2))
            except ValueError:
                continue
    return boxes


def get_model_predictions(model, image_path, conf_threshold=0.5):
    """Get model predictions for an image."""
    results = model(image_path, conf=conf_threshold, verbose=False)
    boxes = results[0].boxes.xyxy.cpu().numpy()
    confs = results[0].boxes.conf.cpu().numpy()
    return boxes, confs


def resize_image(img, target_size):
    """Resize image to fit within target size while maintaining aspect ratio.
    Images are NOT padded to square - they keep their original aspect ratio.
    
    Returns:
        img_resized: The resized image (rectangle, not padded)
        resize_info: Dict with original dimensions and scaling ratio
    """
    h, w = img.shape[:2]
    target_w, target_h = target_size
    
    # Calculate ratio to fit within target dimensions
    ratio_w = target_w / w
    ratio_h = target_h / h
    ratio = min(ratio_w, ratio_h)
    new_w = int(w * ratio)
    new_h = int(h * ratio)
    
    # Resize to fit within target, maintaining aspect ratio (no padding)
    img_resized = cv2.resize(img, (new_w, new_h), interpolation=cv2.INTER_AREA)
    
    resize_info = {
        'orig_w': w,
        'orig_h': h,
        'new_w': new_w,
        'new_h': new_h,
        'ratio': ratio
    }
    
    return img_resized, resize_info


def scale_boxes(boxes, orig_w, orig_h, resize_info):
    """Scale bounding boxes from original image to resized image."""
    ratio = resize_info['ratio']
    return [(int(x1 * ratio), int(y1 * ratio), int(x2 * ratio), int(y2 * ratio)) 
            for x1, y1, x2, y2 in boxes]


def compute_iou(box1, box2):
    """Compute Intersection over Union (IoU) between two bounding boxes."""
    x1_1, y1_1, x2_1, y2_1 = box1
    x1_2, y1_2, x2_2, y2_2 = box2
    
    inter_x1 = max(x1_1, x1_2)
    inter_y1 = max(y1_1, y1_2)
    inter_x2 = min(x2_1, x2_2)
    inter_y2 = min(y2_1, y2_2)
    
    inter_area = max(0, inter_x2 - inter_x1) * max(0, inter_y2 - inter_y1)
    area1 = (x2_1 - x1_1) * (y2_1 - y1_1)
    area2 = (x2_2 - x1_2) * (y2_2 - y1_2)
    union = area1 + area2 - inter_area
    
    if union == 0:
        return 0.0
    
    return inter_area / union


def match_boxes(gt_boxes, pred_boxes, iou_threshold=0.5):
    """Match ground truth and predicted boxes using Hungarian algorithm.
    
    Returns:
        tp_indices: List of (gt_idx, pred_idx) tuples for matched pairs (TP)
        fp_indices: List of pred_idx for unmatched predictions (FP)
        fn_indices: List of gt_idx for unmatched ground truths (FN)
    """
    n_gt = len(gt_boxes)
    n_pred = len(pred_boxes)
    
    if n_gt == 0 and n_pred == 0:
        return [], [], []
    
    # Build IoU matrix
    iou_matrix = np.zeros((n_pred, n_gt))
    for i, pred_box in enumerate(pred_boxes):
        for j, gt_box in enumerate(gt_boxes):
            iou_matrix[i, j] = compute_iou(pred_box, gt_box)
    
    # Use Hungarian algorithm
    row_ind, col_ind = linear_sum_assignment(-iou_matrix)
    
    tp_indices = []
    fp_indices = list(range(n_pred))
    fn_indices = list(range(n_gt))
    
    for i, j in zip(row_ind, col_ind):
        if iou_matrix[i, j] >= iou_threshold:
            tp_indices.append((j, i))
            if j in fn_indices:
                fn_indices.remove(j)
            if i in fp_indices:
                fp_indices.remove(i)
    
    return tp_indices, fp_indices, fn_indices


def process_fp_fn_examples(metrics_csv, model, dataset_path, n_fp=10, n_fn=10, split="test", iou_threshold=0.5):
    """Process FP and FN examples from validation metrics."""
    print("Loading validation metrics...")
    
    metrics_data = []
    with open(metrics_csv, 'r') as f:
        reader = csv.DictReader(f)
        for row in reader:
            metrics_data.append(row)
    
    print(f"Loaded {len(metrics_data)} validation entries")
    
    fp_examples = [r for r in metrics_data if int(r['FP']) > 0]
    fn_examples = [r for r in metrics_data if int(r['FN']) > 0]
    
    print(f"Found {len(fp_examples)} images with FP, {len(fn_examples)} images with FN")
    
    random.seed(42)
    sampled_fp = random.sample(fp_examples, min(n_fp, len(fp_examples)))
    sampled_fn = random.sample(fn_examples, min(n_fn, len(fn_examples)))
    
    print(f"Selected {len(sampled_fp)} FP examples and {len(sampled_fn)} FN examples")
    
    all_samples = []
    
    # Process FP examples
    print("Processing FP examples...")
    for row in tqdm(sampled_fp, desc="FP examples"):
        taxon_id = row['taxon_id']
        image_paths = get_image_paths_for_taxon(taxon_id, split=split)
        
        if not image_paths:
            continue
        
        img_path = image_paths[0]
        label_path = dataset_path / "labels" / split / f"{img_path.stem}.txt"
        
        img = cv2.imread(str(img_path))
        if img is None:
            continue
        
        orig_h, orig_w = img.shape[:2]
        img_resized, resize_info = resize_image(img, IMAGE_SIZE)
        
        gt_boxes = load_ground_truth_boxes(label_path, orig_w, orig_h)
        pred_boxes, _ = get_model_predictions(model, img_path)
        
        # Scale boxes to resized image
        gt_boxes_scaled = scale_boxes(gt_boxes, orig_w, orig_h, resize_info)
        pred_boxes_scaled = scale_boxes(pred_boxes, orig_w, orig_h, resize_info)
        
        # Match boxes
        tp_indices, fp_indices, fn_indices = match_boxes(
            gt_boxes_scaled, pred_boxes_scaled, iou_threshold
        )
        
        # Classify predictions
        pred_classifications = []
        for i in range(len(pred_boxes_scaled)):
            if i in fp_indices:
                pred_classifications.append('FP')
            elif any(pred_idx == i for _, pred_idx in tp_indices):
                pred_classifications.append('TP')
            else:
                pred_classifications.append('unknown')
        
        # Track which GT boxes are FN
        gt_fn_indices = fn_indices
        
        all_samples.append({
            'image': img_resized,
            'gt_boxes': gt_boxes_scaled,
            'pred_boxes': pred_boxes_scaled,
            'gt_fn_indices': gt_fn_indices,
            'pred_classifications': pred_classifications,
            'is_fp_image': True,
            'is_fn_image': False,
            'taxon_id': taxon_id,
            'class': row.get('class', 'Unknown'),
            'specie': row.get('specie', 'Unknown'),
            'fp_count': row['FP'],
            'fn_count': row['FN'],
            'f1': row['F1']
        })
    
    # Process FN examples
    print("Processing FN examples...")
    for row in tqdm(sampled_fn, desc="FN examples"):
        taxon_id = row['taxon_id']
        image_paths = get_image_paths_for_taxon(taxon_id, split=split)
        
        if not image_paths:
            continue
        
        img_path = image_paths[0]
        label_path = dataset_path / "labels" / split / f"{img_path.stem}.txt"
        
        img = cv2.imread(str(img_path))
        if img is None:
            continue
        
        orig_h, orig_w = img.shape[:2]
        img_resized, resize_info = resize_image(img, IMAGE_SIZE)
        
        gt_boxes = load_ground_truth_boxes(label_path, orig_w, orig_h)
        pred_boxes, _ = get_model_predictions(model, img_path)
        
        # Scale boxes to resized image
        gt_boxes_scaled = scale_boxes(gt_boxes, orig_w, orig_h, resize_info)
        pred_boxes_scaled = scale_boxes(pred_boxes, orig_w, orig_h, resize_info)
        
        # Match boxes
        tp_indices, fp_indices, fn_indices = match_boxes(
            gt_boxes_scaled, pred_boxes_scaled, iou_threshold
        )
        
        # Classify predictions
        pred_classifications = []
        for i in range(len(pred_boxes_scaled)):
            if i in fp_indices:
                pred_classifications.append('FP')
            elif any(pred_idx == i for _, pred_idx in tp_indices):
                pred_classifications.append('TP')
            else:
                pred_classifications.append('unknown')
        
        # Track which GT boxes are FN
        gt_fn_indices = fn_indices
        
        all_samples.append({
            'image': img_resized,
            'gt_boxes': gt_boxes_scaled,
            'pred_boxes': pred_boxes_scaled,
            'gt_fn_indices': gt_fn_indices,
            'pred_classifications': pred_classifications,
            'is_fp_image': False,
            'is_fn_image': True,
            'taxon_id': taxon_id,
            'class': row.get('class', 'Unknown'),
            'specie': row.get('specie', 'Unknown'),
            'fp_count': row['FP'],
            'fn_count': row['FN'],
            'f1': row['F1']
        })
    
    return all_samples


def create_grid_visualization(samples, output_path, n_cols=5):
    """Create a grid visualization of FP and FN examples."""
    n_total = len(samples)
    n_rows = (n_total + n_cols - 1) // n_cols
    
    print(f"Creating {n_rows}x{n_cols} grid with {n_total} images")
    
    # Calculate figure size with space for legend
    fig_width = n_cols * 2.5 + 1.2
    fig_height = n_rows * 2.5 + 0.5
    
    fig, axes = plt.subplots(n_rows, n_cols, figsize=(fig_width, fig_height))
    
    if n_rows == 1:
        axes = [axes] if n_cols == 1 else list(axes)
    else:
        axes = [ax for row in axes for ax in row]
    
    for idx, sample in enumerate(samples):
        if idx >= len(axes):
            break
        
        ax = axes[idx]
        img = sample['image']
        gt_boxes = sample.get('gt_boxes', [])
        pred_boxes = sample['pred_boxes']
        gt_fn_indices = sample.get('gt_fn_indices', [])
        pred_classifications = sample['pred_classifications']
        
        # Display image
        ax.imshow(cv2.cvtColor(img, cv2.COLOR_BGR2RGB))
        ax.set_xticks([])
        ax.set_yticks([])
        
        # Draw FN ground truth boxes (teal dashed)
        for j, (x1, y1, x2, y2) in enumerate(gt_boxes):
            if j in gt_fn_indices:
                width = max(1, x2 - x1)
                height = max(1, y2 - y1)
                rect = patches.Rectangle(
                    (x1, y1),
                    width,
                    height,
                    linewidth=1.5,
                    edgecolor=FN_COLOR,
                    facecolor="none",
                    linestyle="--"
                )
                ax.add_patch(rect)
        
        # Draw predicted boxes only (TP or FP)
        for i, (x1, y1, x2, y2) in enumerate(pred_boxes):
            width = max(1, x2 - x1)
            height = max(1, y2 - y1)
            
            if i < len(pred_classifications):
                if pred_classifications[i] == 'FP':
                    color = FP_COLOR
                    linestyle = '--'
                else:  # TP - don't show GT label, just prediction
                    color = TP_COLOR
                    linestyle = '-'
            else:
                color = PRED_COLOR
                linestyle = '--'
            
            rect = patches.Rectangle(
                (x1, y1),
                width,
                height,
                linewidth=1.5,
                edgecolor=color,
                facecolor="none",
                linestyle=linestyle
            )
            ax.add_patch(rect)
    
    # Hide unused subplots
    for idx in range(n_total, len(axes)):
        axes[idx].axis('off')
    
    # Add main title
    plt.suptitle(
        "False Positives and False Negatives - arthro+flatbug model (validation set, IoU>0.5=TP)",
        fontsize=16,
        fontweight="bold",
        y=0.995
    )
    
    # Add row labels (a, b, c, d, ...) on the left
    for i in range(n_rows):
        row_label = chr(ord('a') + i)
        # Position centered in each row, shifted down slightly
        y_pos = 0.92 - (i + 0.5) * 0.90 / n_rows
        fig.text(
            0.015,
            y_pos,
            row_label,
            va='center',
            ha='center',
            fontsize=12,
            fontweight='bold',
            transform=fig.transFigure
        )
    
    # Add column labels (1, 2, 3, 4, 5, ...) centered above each column
    for j in range(n_cols):
        col_label = str(j + 1)
        # Center above each column, shifted right slightly (double correction)
        x_pos = (j + 0.5) * 0.80 / n_cols + 0.04
        fig.text(
            x_pos,
            0.94,
            col_label,
            va='center',
            ha='center',
            fontsize=12,
            fontweight='bold',
            transform=fig.transFigure
        )
    
    # Create legend for bbox colors
    from matplotlib.lines import Line2D
    legend_elements = [
        Line2D([0], [0], color=TP_COLOR, lw=2, label='True Positive (TP)', linestyle='-'),
        Line2D([0], [0], color=FP_COLOR, lw=2, label='False Positive (FP)', linestyle='--'),
        Line2D([0], [0], color=FN_COLOR, lw=2, label='False Negative (FN)', linestyle='--'),
    ]
    
    # Add legend to the right of the figure
    fig.legend(
        handles=legend_elements,
        loc='center right',
        bbox_to_anchor=(1.0, 0.5),
        title='Bounding Box Classification',
        title_fontsize=12,
        fontsize=11,
        frameon=True,
        shadow=False
    )
    
    # Adjust layout
    plt.tight_layout()
    plt.subplots_adjust(
        top=0.90,  # More space for column labels
        bottom=0.02,
        left=0.05,  # More space for row labels
        right=0.82,
        hspace=0.01,
        wspace=0.01
    )
    
    # Save
    plt.savefig(str(output_path), dpi=GRID_DPI, bbox_inches="tight")
    print(f"Saved visualization to: {output_path}")
    
    plt.close()
    print("Done!")


def main():
    """Main function to generate FP and FN visualization grid."""
    # Set font family to match other plots in the project
    plt.rcParams["font.sans-serif"] = ["Nimbus Sans", "DejaVu Sans", "sans-serif"]
    plt.rcParams["font.family"] = "sans-serif"
    
    # Load model
    print("Loading model...")
    model = load_yolo_model(MODEL_PATH)
    
    # Process examples
    samples = process_fp_fn_examples(
        METRICS_CSV, model, DATASET_PATH,
        n_fp=N_FP, n_fn=N_FN, split="test"
    )
    
    # Create grid visualization
    create_grid_visualization(samples, OUTPUT_PNG, n_cols=N_COLS)


if __name__ == "__main__":
    main()
